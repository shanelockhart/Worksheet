// Builds the knowledge module the server imports.
//   inputs : knowledge/instructions.md, knowledge/glossary.md, knowledge/fitment-history.json, public/index.html (data blocks)
//   outputs: knowledge/fitment-site.json, server/knowledge.generated.mjs
// Run automatically by the Netlify build (`npm run build`). The generated module is also committed so the repo works without a build.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => readFileSync(join(root, p), 'utf8');

function extract(html, decl) {
  const start = html.indexOf(`const ${decl} =`);
  if (start < 0) throw new Error(`Could not find ${decl} in public/index.html`);
  const open = html.indexOf(decl === 'fitmentData' ? '{' : '[', start);
  const [o, c] = decl === 'fitmentData' ? ['{', '}'] : ['[', ']'];
  let depth = 0, inStr = null;
  for (let i = open; i < html.length; i++) {
    const ch = html[i];
    if (inStr) { if (ch === '\\') i++; else if (ch === inStr) inStr = null; continue; }
    if (ch === '"' || ch === "'" || ch === '`') { inStr = ch; continue; }
    if (ch === o) depth++;
    else if (ch === c && --depth === 0) return vm.runInNewContext(`(${html.slice(open, i + 1)})`, {}, { timeout: 1000 });
  }
  throw new Error(`Unterminated ${decl}`);
}

const html = read('public/index.html');
const fitment = extract(html, 'fitmentData');
const vendors = extract(html, 'wheelVendorsData');

const site = Object.values(fitment).flatMap((m) =>
  m.vehicles.map((v) => ({ group: m.name, vehicle: v.vehicle, years: v.years, lugPattern: v.lugPattern, centerBore: v.cb, thread: v.thread, offset: v.offset, notes: v.notes || '' })));
writeFileSync(join(root, 'knowledge/fitment-site.json'), JSON.stringify({ source: 'public/index.html fitmentData', vehicles: site, vendors: vendors.map((v) => ({ vendor: v.vendor, brands: v.brands })) }, null, 1) + '\n');

const history = JSON.parse(read('knowledge/fitment-history.json'));
const archive = history.entries.filter((e) => !e.onCurrentSite || (e.conflictingFields || []).length);

const mod = {
  instructions: read('knowledge/instructions.md').trim(),
  glossary: read('knowledge/glossary.md').trim(),
  site,
  vendors: vendors.map((v) => ({ vendor: v.vendor, brands: v.brands })),
  archive: archive.map((e) => ({ manufacturer: e.manufacturer, vehicle: e.vehicle, onCurrentSite: !!e.onCurrentSite, conflictingFields: e.conflictingFields || [], variants: e.variants.map((v) => ({ years: v.years, lugPattern: v.lugPattern, centerBore: v.centerBore, thread: v.thread, offset: v.offset, notes: v.notes || '' })) })),
};
writeFileSync(join(root, 'server/knowledge.generated.mjs'), '// GENERATED by scripts/sync-knowledge.mjs. Do not edit by hand.\nexport default ' + JSON.stringify(mod, null, 1) + ';\n');
console.log(`knowledge synced: ${site.length} site vehicles, ${vendors.length} vendors, ${archive.length} archive entries`);
